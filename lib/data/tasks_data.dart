  // Получить все темы
  static List<String> getTopics() {
    return allTasks.map((task) => task.topic).toSet().toList();
  }

  // Статистика по темам
  static Map<String, int> getTopicsStats() {
    Map<String, int> stats = {};
    for (var task in allTasks) {
      stats[task.topic] = (stats[task.topic] ?? 0) + 1;
    }
    return stats;
