// lib/services/feedback_service.dart

class FeedbackService {
  // Инициализация - пустая заглушка
  static Future<void> init() async {}

  // Вибрация - пустая заглушка
  static Future<void> vibrate({int duration = 50}) async {}

  // Вибрация с паттерном - пустая заглушка
  static Future<void> vibratePattern(List<int> pattern) async {}

  // Обратная связь для правильного ответа - пустая заглушка
  static Future<void> correctFeedback() async {}

  // Обратная связь для неправильного ответа - пустая заглушка
  static Future<void> wrongFeedback() async {}

  // Звук правильного ответа - пустая заглушка
  static Future<void> playCorrectSound() async {}

  // Звук неправильного ответа - пустая заглушка
  static Future<void> playWrongSound() async {}
}
